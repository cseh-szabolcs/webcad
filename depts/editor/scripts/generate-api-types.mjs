#!/usr/bin/env node
// Writes src/api/schema.d.ts from the backend's OpenAPI document. The backend must be running
// (docker compose up); API_DOC_URL overrides where the document is read from.
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, relative, resolve } from 'node:path';
import openapiTS, { astToString } from 'openapi-typescript';

const url = process.env.API_DOC_URL?.trim() || 'http://localhost:8080/_doc.json';
const outFile = resolve(import.meta.dirname, '../src/api/schema.d.ts');

const ast = await openapiTS(new URL(url), {
    // Schemas without a `required` list would otherwise come out all optional.
    propertiesRequiredByDefault: true,
});

await mkdir(dirname(outFile), { recursive: true });
await writeFile(outFile, `/* Generated by \`npm run generate:api\` from ${url}. Do not edit by hand. */\n\n${astToString(ast)}`);

console.log(`Wrote ${relative(process.cwd(), outFile)}`);
